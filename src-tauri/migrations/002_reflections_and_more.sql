-- Рефлексия/дневник дня - один текст на дату, независимо от intervals
-- (не привязана к конкретной клетке, как и предполагалось в задаче:
-- "нажать на иконку блокнота в ячейке ДНЯ", не клетки времени).
CREATE TABLE reflections (
    date        TEXT PRIMARY KEY,   -- ISO 'YYYY-MM-DD'
    text        TEXT NOT NULL,
    updated_at  INTEGER NOT NULL
);


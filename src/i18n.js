export function getLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_KEY) === "en" ? "en" : "ru";
  } catch {
    return "ru";
  }
}

export function setLanguage(language) {
  const nextLanguage = language === "en" ? "en" : "ru";
  try {
    localStorage.setItem(LANGUAGE_KEY, nextLanguage);
  } catch {
    // Keep the in-memory language usable if browser storage is unavailable.
  }
  window.dispatchEvent(new CustomEvent("fmn-language-change", { detail: nextLanguage }));
}

export function t(value, language = getLanguage()) {
  const source = String(value ?? "");
  if (language !== "en") return source;
  const leading = source.match(/^\s*/)?.[0] || "";
  const trailing = source.match(/\s*$/)?.[0] || "";
  const text = source.slice(leading.length, source.length - trailing.length || undefined);
  if (translations[text]) return `${leading}${translations[text]}${trailing}`;
  for (const [pattern, replacement] of dynamicTranslations) {
    if (pattern.test(text)) return `${leading}${text.replace(pattern, replacement)}${trailing}`;
  }
  return source;
}

const I18nContext = createContext({ language: "ru", setLanguage });
export const useI18n = () => useContext(I18nContext);
const domSourceState = new WeakMap();

function installDomTranslations(language) {
  const isExcluded = (node) => {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return !!element?.closest("[data-no-translate], script, style, code, pre");
  };
  const translateNode = (node) => {
    if (isExcluded(node)) return;
    const previous = domSourceState.get(node);
    const current = node.nodeValue;
    const source = previous && current === previous.translated ? previous.source : current;
    const translated = t(source, language);
    if (current !== translated) node.nodeValue = translated;
    domSourceState.set(node, { source, translated });
  };
  const translateElement = (element) => {
    if (isExcluded(element)) return;
    for (const attribute of ["title", "aria-label", "placeholder", "alt"]) {
      if (!element.hasAttribute(attribute)) continue;
      const current = element.getAttribute(attribute);
      const elementState = domSourceState.get(element) || {};
      const previous = elementState[attribute];
      const source = previous && current === previous.translated ? previous.source : current;
      const translated = t(source, language);
      if (current !== translated) element.setAttribute(attribute, translated);
      elementState[attribute] = { source, translated };
      domSourceState.set(element, elementState);
    }
  };
  const scan = (root) => {
    if (isExcluded(root)) return;
    if (root.nodeType === Node.TEXT_NODE) translateNode(root);
    else if (root.nodeType === Node.ELEMENT_NODE) {
      translateElement(root);
      root.childNodes.forEach(scan);
    }
  };
  scan(document.body);
  return new MutationObserver((records) => {
    records.forEach((record) => {
      if (record.type === "characterData") translateNode(record.target);
      else if (record.type === "attributes") translateElement(record.target);
      else record.addedNodes.forEach(scan);
    });
  });
}

export function I18nProvider({ children }) {
  const [language, updateLanguage] = useState(getLanguage);
  useEffect(() => {
    const apply = () => {
      updateLanguage(getLanguage());
    };
    window.addEventListener("fmn-language-change", apply);
    return () => window.removeEventListener("fmn-language-change", apply);
  }, []);
  useEffect(() => {
    const observer = installDomTranslations(language);
    document.documentElement.lang = language;
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["title", "aria-label", "placeholder", "alt"],
    });
    return () => observer.disconnect();
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function LanguageSelector() {
  const { language } = useI18n();
  return createElement(
    "label",
    { className: "field-inline" },
    t("Язык", language),
    createElement(
      "select",
      {
        "aria-label": t("Язык", language),
        value: language,
        onChange: (event) => setLanguage(event.target.value),
        className: "time-input",
      },
      createElement("option", { value: "ru" }, "Русский"),
      createElement("option", { value: "en" }, "English"),
    ),
  );
}
